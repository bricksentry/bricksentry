"""Markdown report for pull-request comments and job summaries."""

from __future__ import annotations

from bricksentry.models import Assessment, TableAssessment, Verdict

MARKER = "<!-- bricksentry-report -->"

_ICON = {
    Verdict.PASS: "🟢",
    Verdict.WARN: "🟡",
    Verdict.NEEDS_HUMAN: "🟠",
    Verdict.BLOCK: "🔴",
}
_TITLE = {
    Verdict.PASS: "Safe to ship",
    Verdict.WARN: "Safe to ship, with warnings",
    Verdict.NEEDS_HUMAN: "Needs human review",
    Verdict.BLOCK: "Blocked",
}


def to_markdown(a: Assessment, max_downstream: int = 15) -> str:
    v = a.verdict
    lines = [
        MARKER,
        f"## {_ICON[v]} bricksentry: {_TITLE[v]}",
        "",
        f"**Risk tier:** `{v.risk_tier}` · **Tables checked:** {len(a.tables)} · **Assessment:** `{a.id}`",
    ]
    if a.notify:
        lines += ["", f"**Review requested from:** {', '.join(a.notify)}"]
    lines.append("")
    if a.hits:
        lines += ["### Why", "", "| Verdict | Rule | Table | Reason |", "|---|---|---|---|"]
        for h in sorted(a.hits, key=lambda h: -h.verdict.rank):
            lines.append(f"| {_ICON[h.verdict]} `{h.verdict.value}` | {h.rule} | `{h.table}` | {_esc(h.reason)} |")
        lines.append("")
    for t in a.tables:
        lines += _table_section(t, max_downstream)
    lines += ["", "<sub>Generated by bricksentry. Verdicts come from policy rules, not from an LLM.</sub>"]
    return "\n".join(lines)


def _table_section(t: TableAssessment, max_downstream: int) -> list[str]:
    out = [f"### {_ICON[t.verdict]} `{t.table}`", "", t.summary, ""]
    d = t.diff
    if d and not d.error:
        out += [
            "| Base rows | Candidate rows | Added | Removed | Changed | Unchanged |",
            "|---:|---:|---:|---:|---:|---:|",
            f"| {d.base_rows:,} | {d.candidate_rows:,} | {d.added_rows:,} | {d.removed_rows:,} | "
            f"{d.changed_rows:,} | {d.unchanged_rows:,} |",
            "",
        ]
        changed_cols = [c for c in d.columns if c.changed_rows or (c.sum_change_pct and abs(c.sum_change_pct) > 0.01)]
        if changed_cols:
            out += ["<details><summary>Column changes</summary>", "",
                    "| Column | Rows changed | Nulls (base → cand.) | Sum change |", "|---|---:|---|---:|"]
            for c in sorted(changed_cols, key=lambda c: -c.changed_rows):
                sc = f"{c.sum_change_pct:+.2f}%" if c.sum_change_pct is not None else "–"
                out.append(f"| `{c.column}` | {c.changed_rows:,} | {c.base_nulls} → {c.candidate_nulls} | {sc} |")
            samples = [c for c in changed_cols if c.samples]
            if samples:
                out += ["", "**Sample changes**", ""]
                for c in samples[:3]:
                    for s in c.samples[:3]:
                        key = ", ".join(f"{k}={s.get(k)}" for k in d.keys)
                        out.append(f"- `{c.column}` @ {key}: `{s.get('base_value')}` → `{s.get('candidate_value')}`")
            out += ["", "</details>", ""]
    if t.downstream:
        out += [f"<details><summary>Blast radius: {len(t.downstream)} downstream asset(s)</summary>", "",
                "| Depth | Kind | Name | Owner | Tags |", "|---:|---|---|---|---|"]
        for n in sorted(t.downstream, key=lambda n: (n.depth, n.kind))[:max_downstream]:
            tags = ", ".join(f"{k}={v}" if v else k for k, v in n.tags.items()) or "–"
            out.append(f"| {n.depth} | {n.kind} | `{n.name}` | {n.owner or '–'} | {tags} |")
        if len(t.downstream) > max_downstream:
            out.append(f"| … | | {len(t.downstream) - max_downstream} more | | |")
        out += ["", "</details>", ""]
    tagged = [c for c in t.changed_columns if t.column_tags.get(c)]
    if tagged or t.column_downstream:
        out += [f"<details><summary>Column impact: {len(t.changed_columns)} changed column(s), "
                f"{len(t.column_downstream)} downstream column(s)</summary>", ""]
        if tagged:
            out += ["**Tagged columns changed:** " + ", ".join(
                f"`{c}` ({', '.join(f'{k}={v}' if v else k for k, v in t.column_tags[c].items())})" for c in tagged), ""]
        if t.column_downstream:
            out += ["| Changed column | Feeds | Depth | Tags |", "|---|---|---:|---|"]
            for c in sorted(t.column_downstream, key=lambda c: (c.depth, c.table, c.column))[:max_downstream]:
                tags = ", ".join(f"{k}={v}" if v else k for k, v in c.tags.items()) or "–"
                out.append(f"| `{c.source_column}` | `{c.table}.{c.column}` | {c.depth} | {tags} |")
            if len(t.column_downstream) > max_downstream:
                out.append(f"| … | {len(t.column_downstream) - max_downstream} more | | |")
        out += ["", "</details>", ""]
    if t.rollback and t.rollback.startswith("RESTORE"):
        if t.rollback_warning:
            out += [f"> :warning: **Before you restore:** {t.rollback_warning}", ""]
        out += ["**Rollback:**", "```sql", t.rollback, "```", ""]
    elif t.rollback:
        out += [f"**Rollback:** {t.rollback}", ""]
    return out


def _esc(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")
